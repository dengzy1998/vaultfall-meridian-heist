// Parse one floor plan into a grid plus entity spawn points (tile coords).
export function parseFloor(def) {
  const grid = def.plan.map((row) => row.split(''));
  const found = {
    player: { x: 2, y: 19 },
    vault: { x: 34, y: 18 },
    exit: { x: 38, y: 18 },
    guards: [],
    waypoints: [],
    cameras: [],
    lootSpots: [],
    boss: null,
  };
  for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
      const ch = grid[y][x];
      if (ch === 'P') { found.player = { x, y }; grid[y][x] = '.'; }
      else if (ch === 'V') { found.vault = { x, y }; grid[y][x] = 'V'; }
      else if (ch === 'X') { found.exit = { x, y }; grid[y][x] = 'X'; }
      else if (ch === 'G') { found.guards.push({ x, y }); grid[y][x] = '.'; }
      else if (ch === 'g') { found.waypoints.push({ x, y }); grid[y][x] = '.'; }
      else if (ch === 'C') { found.cameras.push({ x, y }); grid[y][x] = '.'; }
      else if (ch === 'L') { found.lootSpots.push({ x, y }); grid[y][x] = '.'; }
      else if (ch === 'B') { found.boss = { x, y }; grid[y][x] = '.'; }
    }
  }
  return { def, grid, ...found };
}

export function tileCenter(tx, ty) {
  return { x: tx * CONFIG.tile + CONFIG.tile / 2, y: ty * CONFIG.tile + CONFIG.tile / 2 };
}
