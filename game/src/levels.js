// Floor plans. One job: the five ASCII room layouts of the Meridian.
// Glyphs: # wall · . floor · D desk (cover, blocks sight) · V vault · X exit
//         P player start · G guard spawn · g patrol waypoint · C camera
//         L loot spot · B boss spawn. Plans are normalised to 40x21 and a
//         closed border, so a miscounted row can never break the game.
import { CONFIG } from './config.js';

const COLS = CONFIG.cols;
const ROWS = CONFIG.rows;

function normalise(rows) {
  const out = [];
  for (let r = 0; r < ROWS; r++) {
    let row = (rows[r] || '').padEnd(COLS, '.').slice(0, COLS);
    if (r === 0 || r === ROWS - 1) row = '#'.repeat(COLS);
    else row = '#' + row.slice(1, COLS - 1) + '#';
    out.push(row);
  }
  return out;
}

